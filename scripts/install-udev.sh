#!/usr/bin/env bash
# Grant the active user write access to Sony DualShock 4 LED brightness files.
#
# Usage:
#   sudo ./scripts/install-udev.sh [username]
#
# The username defaults to $SUDO_USER (the user who invoked sudo).
# Undo with:
#   sudo rm /etc/udev/rules.d/99-dualshock4-led.rules

set -euo pipefail

if (( EUID != 0 )); then
    exec sudo -- "$0" "$@"
fi

TARGET_USER="${SUDO_USER:-}"
if [[ -z "$TARGET_USER" || "$TARGET_USER" == "root" ]]; then
    TARGET_USER="${1:-}"
fi
if [[ -z "$TARGET_USER" ]]; then
    echo "Error: run this with sudo as your normal user, or pass a username." >&2
    echo "  sudo $0 <username>" >&2
    exit 1
fi
if ! id "$TARGET_USER" >/dev/null 2>&1; then
    echo "Error: no such user: $TARGET_USER" >&2
    exit 1
fi

TARGET_GROUP="$(id -gn "$TARGET_USER")"
RULE_FILE=/etc/udev/rules.d/99-dualshock4-led.rules
TMP_RULE="$(mktemp)"
trap 'rm -f "$TMP_RULE"' EXIT

cat > "$TMP_RULE" <<RULE
# Generated by ds4-tui/scripts/install-udev.sh.
# Give $TARGET_USER (group $TARGET_GROUP) write access to Sony DS4 LEDs.
# Sony USB vendor ID is 054c.
SUBSYSTEM=="leds", ACTION=="add|change", KERNEL=="*:red", ATTRS{idVendor}=="054c", RUN+="/bin/chgrp $TARGET_GROUP /sys/class/leds/%k/brightness", RUN+="/bin/chmod 0660 /sys/class/leds/%k/brightness"
SUBSYSTEM=="leds", ACTION=="add|change", KERNEL=="*:green", ATTRS{idVendor}=="054c", RUN+="/bin/chgrp $TARGET_GROUP /sys/class/leds/%k/brightness", RUN+="/bin/chmod 0660 /sys/class/leds/%k/brightness"
SUBSYSTEM=="leds", ACTION=="add|change", KERNEL=="*:blue", ATTRS{idVendor}=="054c", RUN+="/bin/chgrp $TARGET_GROUP /sys/class/leds/%k/brightness", RUN+="/bin/chmod 0660 /sys/class/leds/%k/brightness"
SUBSYSTEM=="leds", ACTION=="add|change", KERNEL=="*:global", ATTRS{idVendor}=="054c", RUN+="/bin/chgrp $TARGET_GROUP /sys/class/leds/%k/brightness", RUN+="/bin/chmod 0660 /sys/class/leds/%k/brightness"
RULE

if [[ -f "$RULE_FILE" ]]; then
    cp -a "$RULE_FILE" "$RULE_FILE.bak.$(date +%s)"
fi
install -m 0644 "$TMP_RULE" "$RULE_FILE"

# Apply immediately to a controller that is already connected.
shopt -s nullglob
changed=0
for kind in red green blue global; do
    for file in /sys/class/leds/*:"$kind"/brightness; do
        target="$(readlink -f "$file" 2>/dev/null || true)"
        [[ "$target" == *054C* ]] || continue
        chgrp "$TARGET_GROUP" "$file" 2>/dev/null || true
        chmod 0660 "$file" 2>/dev/null || true
        changed=$((changed + 1))
    done
done

if command -v udevadm >/dev/null 2>&1; then
    udevadm control --reload-rules
    udevadm trigger --subsystem-match=leds --action=change || true
fi

echo "Installed $RULE_FILE"
echo "Access group: $TARGET_GROUP   User: $TARGET_USER"
if (( changed > 0 )); then
    echo "Updated $changed currently connected LED file(s)."
else
    echo "No Sony LED files were present; connect the controller and replug it once."
fi
echo
echo "In ds4-tui, press r to rescan. The badge should become DS4 READY,"
echo "and apply/rainbow will no longer ask for sudo."
